  /* ─── Cập nhật ngôn ngữ tất cả badges đang hiển thị ────────── */
  function updateAllBadgesLanguage(lang) {
    // Cập nhật standard và full badge labels
    var badges = document.querySelectorAll('.ai-badge[data-ai-type][data-ai-variant]');
    badges.forEach(function (badge) {
      var type    = badge.getAttribute('data-ai-type');
      var variant = badge.getAttribute('data-ai-variant');
      var cfg     = AI_TYPES[type];
      if (!cfg) return;

      if (type === 'ai:translated') {
        badge.style.display = (lang === 'vi') ? 'none' : '';
      }

      var labelEl = badge.querySelector('.ai-badge-label');
      if (!labelEl) return;

      if (variant === 'full' || variant === 'standard') {
        labelEl.textContent = (lang === 'en') ? cfg.en : cfg.vi;
      }
      // micro/inline: luôn hiển thị "AI" — không đổi
    });

    // Cập nhật Disclosure Box
    var boxes = document.querySelectorAll('.ai-disclosure-box');
    boxes.forEach(function (box) {
      var boxType = box.getAttribute('data-ai-type');
      if (boxType === 'ai:translated') {
        box.style.display = (lang === 'vi') ? 'none' : '';
      }
      
      // Title
      var titleEl = box.querySelector('.ai-disclosure-title-text');
      if (titleEl) {
        titleEl.textContent = (lang === 'en') ? titleEl.getAttribute('data-en') : titleEl.getAttribute('data-vi');
      }
      // Toggle text
      var toggleEl = box.querySelector('.ai-disclosure-toggle-text');
      if (toggleEl) {
        toggleEl.textContent = (lang === 'en') ? toggleEl.getAttribute('data-en') : toggleEl.getAttribute('data-vi');
      }
      // Body paragraph
      var bodyEl = box.querySelector('.ai-disclosure-text p');
      if (bodyEl) {
        bodyEl.textContent = (lang === 'en') ? bodyEl.getAttribute('data-en') : bodyEl.getAttribute('data-vi');
      }
      // Learn more link
      var learnEl = box.querySelector('.ai-disclosure-learn-more');
      if (learnEl) {
        learnEl.textContent = (lang === 'en') ? learnEl.getAttribute('data-en') : learnEl.getAttribute('data-vi');
      }
    });
  }

  /* ─── ĐIỂM TÍCH HỢP 1: Single Post Header (Full Badge + Disclosure Box) */
  function injectSinglePostBadge() {
    var container = document.getElementById('single-post-wrapper');
    if (container) {
      if (container.style.display === 'none') return;
    } else {
      container = document.querySelector('.single-post-container');
      if (!container) return;
    }

    // Đọc ai type từ data attribute trên container hoặc bài viết
    var rawType = container.getAttribute('data-ai-type');
    if (!rawType) {
      var childWithAI = container.querySelector('[data-ai-type]');
      if (childWithAI) rawType = childWithAI.getAttribute('data-ai-type');
    }
    if (!rawType) {
      var rawLabels = container.querySelectorAll('.post-raw-label');
      var allLabels = [];
      for (var i = 0; i < rawLabels.length; i++) {
        allLabels.push(rawLabels[i].textContent);
      }
      var t = extractAITypesFromLabels(allLabels);
      if (t) { rawType = t; container.setAttribute('data-ai-type', t); }
    }
    if (!rawType) return;
    var aiTypes = rawType.split(',').filter(function(t) { return AI_TYPES[t]; });
    if (!aiTypes.length) return;

    var lang = getCurrentLang();

    // (A) Inject Full Badge vào author-meta-details
    var metaDetails = container.querySelector('.author-meta-details');
    if (metaDetails && !metaDetails.querySelector('.ai-badge-full')) {
      for (var k = 0; k < aiTypes.length; k++) {
        var aiType = aiTypes[k];
        var sepEl = document.createElement('span');
        sepEl.textContent = '•';
        metaDetails.appendChild(sepEl);

        var wrapper = document.createElement('span');
        wrapper.innerHTML = renderAIBadge(aiType, 'full', lang);
        metaDetails.appendChild(wrapper);
        initFullBadgeToggle(wrapper.querySelector('.ai-badge-full'));
      }
    }

    // (B) Inject Disclosure Box sau .post-body
    var postBody = container.querySelector('.post-body');

    if (postBody && !container.querySelector('.ai-disclosure-box')) {
      // Loop ngược để chèn vào sau postBody đúng thứ tự (vì insertBefore)
      for (var k = aiTypes.length - 1; k >= 0; k--) {
        var aiType = aiTypes[k];
        var discEl = document.createElement('div');
        discEl.innerHTML = renderDisclosureBox(aiType, lang);
        postBody.parentNode.insertBefore(discEl.firstChild, postBody.nextSibling);
      }
      initDisclosureBoxToggle();
    }
  }

  /* Toggle Full Badge → mở/đóng Disclosure Box */
  function initFullBadgeToggle(badgeEl) {
    if (!badgeEl) return;
    badgeEl.addEventListener('click', function () {
      var box = document.getElementById('ai-disclosure-box-' + badgeEl.getAttribute('data-ai-type').replace(':', '-'));
      if (!box) return;
      var isOpen = box.classList.toggle('is-open');
      badgeEl.setAttribute('aria-expanded', isOpen);
      badgeEl.classList.toggle('is-open', isOpen);
    });
  }

  /* Toggle Disclosure Box header */
  function initDisclosureBoxToggle() {
    var headers = document.querySelectorAll('.ai-disclosure-header');
    if (!headers.length) return;
    headers.forEach(function(header) {
      if (header.dataset.hasToggleInit) return;
      header.dataset.hasToggleInit = 'true';

    function toggle() {
      var box = header.closest('.ai-disclosure-box');
      if (!box) return;
      var isOpen = box.classList.toggle('is-open');
      header.setAttribute('aria-expanded', isOpen);
    }

    header.addEventListener('click', toggle);
    header.addEventListener('keydown', function (e) {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          toggle();
        }
      });
    });
  }

  /* ─── ĐIỂM TÍCH HỢP 2: Post Cards Feed (Standard Badge) ────── */
  function injectPostCardBadges() {
    var lang = getCurrentLang();
    var cards = document.querySelectorAll('.post-card');
    cards.forEach(function (card) {
      var rawType = card.getAttribute('data-ai-type');
      if (!rawType) {
        var rawLabels = card.querySelectorAll('.post-raw-label');
        var allLabels = [];
        for (var i = 0; i < rawLabels.length; i++) {
          allLabels.push(rawLabels[i].textContent);
        }
        var t = extractAITypesFromLabels(allLabels);
        if (t) { rawType = t; card.setAttribute('data-ai-type', t); }
      }
      if (!rawType) return;
      var aiTypes = rawType.split(',').filter(function(t) { return AI_TYPES[t]; });
      if (!aiTypes.length) return;

      var meta = card.querySelector('.post-card-meta');
      if (!meta) return;
      if (meta.querySelector('.ai-badge-standard')) return;

      for (var k = 0; k < aiTypes.length; k++) {
        var aiType = aiTypes[k];
        var sepEl = document.createElement('span');
        sepEl.textContent = '•';

        var wrapper = document.createElement('span');
        wrapper.style.display = 'inline-flex';
        wrapper.innerHTML = renderAIBadge(aiType, 'standard', lang);

        meta.appendChild(sepEl);
        meta.appendChild(wrapper);
      }
    });
  }

