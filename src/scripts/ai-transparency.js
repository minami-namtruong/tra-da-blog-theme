/* ==========================================
   AI TRANSPARENCY SYSTEM — FEAT-AI-TRANSPARENCY-V1
   Spec: specs/AI_TRANSPARENCY_SPECIFICATION.md
   
   Chức năng:
   - Nhận diện nhãn ai:assisted / ai:product / ai:generated
   - Render 4 biến thể badge: full, standard, micro, inline
   - Render Khung Thông Cáo Minh Bạch (Disclosure Box) ở đầu bài
   - Hỗ trợ song ngữ VI/EN, tự động cập nhật khi languageChanged
   - Hoàn toàn độc lập, không ảnh hưởng đến filter/category logic
   ========================================== */
(function () {
  'use strict';

  /* ─── Cấu hình nhãn AI ─────────────────────────────────────── */
  var AI_TYPES = {
    'ai:assisted':  { icon: '✨', vi: 'Hỗ trợ bởi AI', en: 'AI-Assisted'  },
    'ai:product':   { icon: '🤖', vi: 'Sản phẩm AI',   en: 'AI Product'   },
    'ai:generated': { icon: '⚡', vi: 'Tạo bởi AI',    en: 'AI-Generated' },
  };

  /* Nội dung Khung Thông Cáo Minh Bạch */
  var DISCLOSURE_TEXT = {
    'ai:assisted': {
      vi: 'Bài viết này được thực hiện với sự hỗ trợ của công cụ Trí tuệ Nhân tạo (AI) trong khâu nghiên cứu tư liệu, tra cứu dữ liệu và gợi ý cấu trúc dàn ý. Toàn bộ góc nhìn, trải nghiệm thực tế, văn phong và việc kiểm chứng tính chính xác của thông tin đều do Nam Trương trực tiếp thực hiện và chịu trách nhiệm.',
      en: 'This article was researched and outlined with the assistance of Artificial Intelligence (AI) tools. All viewpoints, personal insights, narrative voice, and rigorous fact-checking are conducted and owned entirely by Nam Truong.',
    },
    'ai:product': {
      vi: 'Bài viết này là đánh giá, trải nghiệm thực tế của tác giả về một sản phẩm hoặc công cụ AI. Mọi nhận xét đều dựa trên trải nghiệm cá nhân, không bị ảnh hưởng bởi nhà sản xuất.',
      en: 'This article is an honest review and personal experience of an AI product or tool. All opinions are based on personal use and are independent from the product makers.',
    },
    'ai:generated': {
      vi: 'Toàn bộ hoặc phần lớn nội dung của bài viết này được tổng hợp bởi AI theo yêu cầu của tác giả, nhằm mục đích thử nghiệm công nghệ và nghiên cứu. Tác giả chịu trách nhiệm về việc lựa chọn và công bố nội dung.',
      en: 'Most or all of this article\'s content was generated by AI as a technology experiment directed by the author. The author takes responsibility for selecting and publishing this content.',
    },
  };

  /* ─── Nhận diện ngôn ngữ hiện tại ──────────────────────────── */
  function getCurrentLang() {
    try {
      return localStorage.getItem('user_lang') || 'vi';
    } catch (e) {
      return 'vi';
    }
  }

  /* ─── Chuẩn hóa nhãn AI (không phân biệt hoa thường, hỗ trợ dấu gạch ngang) */
  function normalizeAILabel(str) {
    if (!str) return '';
    return str.toLowerCase().replace(/-/g, ':');
  }

  /* ─── Phát hiện loại AI từ chuỗi nhãn đơn ─────────────────── */
  function detectAIType(labelStr) {
    var normalized = normalizeAILabel(labelStr.trim());
    // Khớp trực tiếp
    if (AI_TYPES[normalized]) return normalized;
    // Khớp từng key
    var keys = Object.keys(AI_TYPES);
    for (var i = 0; i < keys.length; i++) {
      if (normalized.indexOf(keys[i].replace(':', ':')) === 0 ||
          normalized.indexOf(keys[i].replace(':', '-')) === 0) {
        return keys[i];
      }
    }
    return null;
  }

  /* ─── Phát hiện loại AI từ mảng nhãn ───────────────────────── */
  function detectAITypeFromLabels(labels) {
    if (!labels || !labels.length) return null;
    for (var i = 0; i < labels.length; i++) {
      var raw = (typeof labels[i] === 'string') ? labels[i] : (labels[i].name || '');
      var type = detectAIType(raw);
      if (type) return type;
    }
    return null;
  }

  /* ─── Render Badge HTML ─────────────────────────────────────── */
  /**
   * @param {string} type     - 'ai:assisted' | 'ai:product' | 'ai:generated'
   * @param {string} variant  - 'full' | 'standard' | 'micro' | 'inline'
   * @param {string} lang     - 'vi' | 'en'
   * @returns {string} HTML string
   */
  function renderAIBadge(type, variant, lang) {
    type = detectAIType(type) || type;
    var cfg = AI_TYPES[type];
    if (!cfg) return '';

    var label = (lang === 'en') ? cfg.en : cfg.vi;
    var icon  = cfg.icon;

    if (variant === 'inline') {
      return (
        '<span class="ai-badge ai-badge-inline" data-ai-type="' + type + '" data-ai-variant="inline">' +
          '<span class="ai-badge-icon">' + icon + '</span>' +
          '<span class="ai-badge-label">AI</span>' +
        '</span>'
      );
    }

    if (variant === 'micro') {
      return (
        '<span class="ai-badge ai-badge-micro" data-ai-type="' + type + '" data-ai-variant="micro">' +
          '<span class="ai-badge-icon">' + icon + '</span>' +
          '<span class="ai-badge-label">AI</span>' +
        '</span>'
      );
    }

    if (variant === 'full') {
      return (
        '<button type="button" class="ai-badge ai-badge-full" data-ai-type="' + type + '" data-ai-variant="full" aria-expanded="false">' +
          '<span class="ai-badge-icon">' + icon + '</span>' +
          '<span class="ai-badge-label">' + label + '</span>' +
          '<span class="ai-badge-chevron">▾</span>' +
        '</button>'
      );
    }

    // standard (default)
    return (
      '<span class="ai-badge ai-badge-standard" data-ai-type="' + type + '" data-ai-variant="standard">' +
        '<span class="ai-badge-icon">' + icon + '</span>' +
        '<span class="ai-badge-label">' + label + '</span>' +
      '</span>'
    );
  }

  /* ─── Render Disclosure Box HTML ────────────────────────────── */
  function renderDisclosureBox(type, lang) {
    type = detectAIType(type) || type;
    var cfg  = AI_TYPES[type];
    var disc = DISCLOSURE_TEXT[type];
    if (!cfg || !disc) return '';

    var label    = (lang === 'en') ? cfg.en : cfg.vi;
    var bodyText = (lang === 'en') ? disc.en : disc.vi;
    var titleVI  = '✦ THÔNG CÁO MINH BẠCH VỀ NỘI DUNG';
    var titleEN  = '✦ AI TRANSPARENCY DISCLOSURE';
    var title    = (lang === 'en') ? titleEN : titleVI;
    var learnVI  = 'ℹ️ Tìm hiểu thêm về Chính sách AI của chúng tôi »';
    var learnEN  = 'ℹ️ Learn more about our AI Policy »';
    var learnTxt = (lang === 'en') ? learnEN : learnVI;
    var toggleVI = 'Xem chi tiết';
    var toggleEN = 'Details';
    var toggleTxt = (lang === 'en') ? toggleEN : toggleVI;

    return (
      '<div class="ai-disclosure-box" data-ai-type="' + type + '" id="ai-disclosure-box">' +
        '<div class="ai-disclosure-header" id="ai-disclosure-header" role="button" tabindex="0" aria-expanded="false" aria-controls="ai-disclosure-body">' +
          '<div class="ai-disclosure-title">' +
            '<span class="ai-disclosure-icon">' + cfg.icon + '</span>' +
            '<span class="ai-disclosure-title-text" data-vi="' + titleVI + '" data-en="' + titleEN + '">' + title + '</span>' +
          '</div>' +
          '<button type="button" class="ai-disclosure-toggle" aria-controls="ai-disclosure-body">' +
            '<span class="ai-disclosure-toggle-text" data-vi="' + toggleVI + '" data-en="' + toggleEN + '">' + toggleTxt + '</span>' +
            '<span class="ai-disclosure-toggle-icon">▾</span>' +
          '</button>' +
        '</div>' +
        '<div class="ai-disclosure-body" id="ai-disclosure-body">' +
          '<div class="ai-disclosure-text">' +
            '<p data-vi="' + escapeAttr(disc.vi) + '" data-en="' + escapeAttr(disc.en) + '">' + escapeHtml(bodyText) + '</p>' +
            '<a href="#" class="ai-disclosure-learn-more" data-vi="' + escapeAttr(learnVI) + '" data-en="' + escapeAttr(learnEN) + '">' + escapeHtml(learnTxt) + '</a>' +
          '</div>' +
        '</div>' +
      '</div>'
    );
  }

  /* ─── Cập nhật ngôn ngữ tất cả badges đang hiển thị ────────── */
  function updateAllBadgesLanguage(lang) {
    // Cập nhật standard và full badge labels
    var badges = document.querySelectorAll('.ai-badge[data-ai-type][data-ai-variant]');
    badges.forEach(function (badge) {
      var type    = badge.getAttribute('data-ai-type');
      var variant = badge.getAttribute('data-ai-variant');
      var cfg     = AI_TYPES[type];
      if (!cfg) return;

      var labelEl = badge.querySelector('.ai-badge-label');
      if (!labelEl) return;

      if (variant === 'full' || variant === 'standard') {
        labelEl.textContent = (lang === 'en') ? cfg.en : cfg.vi;
      }
      // micro/inline: luôn hiển thị "AI" — không đổi
    });

    // Cập nhật Disclosure Box
    var box = document.getElementById('ai-disclosure-box');
    if (box) {
      // Title
      var titleEl = box.querySelector('.ai-disclosure-title-text');
      if (titleEl) {
        titleEl.textContent = (lang === 'en') ? titleEl.getAttribute('data-en') : titleEl.getAttribute('data-vi');
      }
      // Toggle text
      var toggleEl = box.querySelector('.ai-disclosure-toggle-text');
      if (toggleEl) {
        toggleEl.textContent = (lang === 'en') ? toggleEl.getAttribute('data-en') : toggleEl.getAttribute('data-vi');
      }
      // Body paragraph
      var bodyEl = box.querySelector('.ai-disclosure-text p');
      if (bodyEl) {
        bodyEl.textContent = (lang === 'en') ? bodyEl.getAttribute('data-en') : bodyEl.getAttribute('data-vi');
      }
      // Learn more link
      var learnEl = box.querySelector('.ai-disclosure-learn-more');
      if (learnEl) {
        learnEl.textContent = (lang === 'en') ? learnEl.getAttribute('data-en') : learnEl.getAttribute('data-vi');
      }
    }
  }

  /* ─── ĐIỂM TÍCH HỢP 1: Single Post Header (Full Badge + Disclosure Box) */
  function injectSinglePostBadge() {
    var container = document.getElementById('single-post-wrapper');
    if (container) {
      if (container.style.display === 'none') return;
    } else {
      container = document.querySelector('.single-post-container');
      if (!container) return;
    }

    // Đọc ai type từ data attribute trên container hoặc bài viết
    var rawType = container.getAttribute('data-ai-type');
    if (!rawType) {
      var childWithAI = container.querySelector('[data-ai-type]');
      if (childWithAI) rawType = childWithAI.getAttribute('data-ai-type');
    }
    if (!rawType) return;
    var aiType = detectAIType(rawType);
    if (!aiType || !AI_TYPES[aiType]) return;

    var lang = getCurrentLang();

    // (A) Inject Full Badge vào author-meta-details
    var metaDetails = container.querySelector('.author-meta-details');
    if (metaDetails && !metaDetails.querySelector('.ai-badge-full')) {
      // Thêm dấu phân cách và badge
      var sepEl = document.createElement('span');
      sepEl.textContent = '•';
      metaDetails.appendChild(sepEl);

      var wrapper = document.createElement('span');
      wrapper.innerHTML = renderAIBadge(aiType, 'full', lang);
      metaDetails.appendChild(wrapper);

      // Gắn sự kiện toggle cho Full Badge
      initFullBadgeToggle(wrapper.querySelector('.ai-badge-full'));
    }

    // (B) Inject Disclosure Box trước .post-body (hoặc trước AdSense top)
    var postBody = container.querySelector('.post-body');
    var adsenseTop = container.querySelector('.adsense-slot.adsense-top, .adsense-top');
    var insertBefore = adsenseTop || postBody;

    if (insertBefore && !container.querySelector('#ai-disclosure-box')) {
      var discEl = document.createElement('div');
      discEl.innerHTML = renderDisclosureBox(aiType, lang);
      insertBefore.parentNode.insertBefore(discEl.firstChild, insertBefore);

      // Gắn sự kiện toggle cho Disclosure Box
      initDisclosureBoxToggle();
    }
  }

  /* Toggle Full Badge → mở/đóng Disclosure Box */
  function initFullBadgeToggle(badgeEl) {
    if (!badgeEl) return;
    badgeEl.addEventListener('click', function () {
      var box = document.getElementById('ai-disclosure-box');
      if (!box) return;
      var isOpen = box.classList.toggle('is-open');
      badgeEl.setAttribute('aria-expanded', isOpen);
      badgeEl.classList.toggle('is-open', isOpen);
    });
  }

  /* Toggle Disclosure Box header */
  function initDisclosureBoxToggle() {
    var header = document.getElementById('ai-disclosure-header');
    if (!header) return;

    function toggle() {
      var box = header.closest('.ai-disclosure-box');
      if (!box) return;
      var isOpen = box.classList.toggle('is-open');
      header.setAttribute('aria-expanded', isOpen);
    }

    header.addEventListener('click', toggle);
    header.addEventListener('keydown', function (e) {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        toggle();
      }
    });
  }

  /* ─── ĐIỂM TÍCH HỢP 2: Post Cards Feed (Standard Badge) ────── */
  function injectPostCardBadges() {
    var lang = getCurrentLang();
    var cards = document.querySelectorAll('.post-card[data-ai-type]');
    cards.forEach(function (card) {
      var rawType = card.getAttribute('data-ai-type');
      var aiType = detectAIType(rawType);
      if (!aiType || !AI_TYPES[aiType]) return;

      var meta = card.querySelector('.post-card-meta');
      if (!meta) return;

      // Tránh inject trùng
      if (meta.querySelector('.ai-badge-standard')) return;

      // Thêm separator và badge
      var sepEl = document.createElement('span');
      sepEl.textContent = '•';

      var wrapper = document.createElement('span');
      wrapper.style.display = 'inline-flex';
      wrapper.innerHTML = renderAIBadge(aiType, 'standard', lang);

      meta.appendChild(sepEl);
      meta.appendChild(wrapper);
    });
  }

  /* ─── ĐIỂM TÍCH HỢP 3: Archive Timeline (Micro Badge) ──────── */
  function injectTimelineBadges() {
    var lang = getCurrentLang();
    // archive-page.js đã render .archive-post-card với data-ai-type
    var cards = document.querySelectorAll('.archive-post-card[data-ai-type]');
    cards.forEach(function (card) {
      var rawType = card.getAttribute('data-ai-type');
      var aiType = detectAIType(rawType);
      if (!aiType || !AI_TYPES[aiType]) return;

      // Tránh inject trùng
      if (card.querySelector('.ai-badge-micro')) return;

      // Tìm title span và inject badge ngay sau
      var titleEl = card.querySelector('.archive-post-card-title');
      if (!titleEl) return;

      var wrapper = document.createElement('span');
      wrapper.innerHTML = renderAIBadge(aiType, 'micro', lang);
      titleEl.after(wrapper.firstChild);
    });
  }

  /* ─── ĐIỂM TÍCH HỢP 4: Special Post Widgets (Inline Badge) ─── */
  function injectWidgetBadges() {
    var lang = getCurrentLang();

    // Ranked widget: inject vào .sp-ranked-date
    var rankedDates = document.querySelectorAll('.sp-ranked-item[data-ai-type] .sp-ranked-date');
    rankedDates.forEach(function (dateEl) {
      var item = dateEl.closest('[data-ai-type]');
      if (!item) return;
      var rawType = item.getAttribute('data-ai-type');
      var aiType = detectAIType(rawType);
      if (!aiType || !AI_TYPES[aiType]) return;
      if (dateEl.querySelector('.ai-badge-inline')) return;

      var sepEl = document.createElement('span');
      sepEl.textContent = ' • ';
      var wrapper = document.createElement('span');
      wrapper.innerHTML = renderAIBadge(aiType, 'inline', lang);
      dateEl.appendChild(sepEl);
      dateEl.appendChild(wrapper.firstChild);
    });

    // Spotlight widget: inject vào .sp-spotlight-meta
    var spotlightMetas = document.querySelectorAll('.sp-spotlight-card[data-ai-type] .sp-spotlight-meta');
    spotlightMetas.forEach(function (metaEl) {
      var card = metaEl.closest('[data-ai-type]');
      if (!card) return;
      var rawType = card.getAttribute('data-ai-type');
      var aiType = detectAIType(rawType);
      if (!aiType || !AI_TYPES[aiType]) return;
      if (metaEl.querySelector('.ai-badge-standard')) return;

      var wrapper = document.createElement('span');
      wrapper.innerHTML = renderAIBadge(aiType, 'standard', lang);
      metaEl.appendChild(wrapper.firstChild);
    });

    // Digest widget: inject vào .sp-digest-timestamp
    var digestTimestamps = document.querySelectorAll('.sp-digest-item[data-ai-type] .sp-digest-timestamp');
    digestTimestamps.forEach(function (tsEl) {
      var item = tsEl.closest('[data-ai-type]');
      if (!item) return;
      var rawType = item.getAttribute('data-ai-type');
      var aiType = detectAIType(rawType);
      if (!aiType || !AI_TYPES[aiType]) return;
      if (tsEl.querySelector('.ai-badge-inline')) return;

      var sepEl = document.createElement('span');
      sepEl.textContent = ' • ';
      var wrapper = document.createElement('span');
      wrapper.innerHTML = renderAIBadge(aiType, 'inline', lang);
      tsEl.appendChild(sepEl);
      tsEl.appendChild(wrapper.firstChild);
    });
  }

  /* ─── Khởi chạy toàn bộ injection ─────────────────────────── */
  function initAITransparency() {
    injectSinglePostBadge();
    injectPostCardBadges();
    injectTimelineBadges();
    injectWidgetBadges();
  }

  /* ─── Lắng nghe sự kiện languageChanged từ bilingual.js ─────── */
  window.addEventListener('languageChanged', function (e) {
    var lang = (e.detail && e.detail.lang) ? e.detail.lang : getCurrentLang();
    updateAllBadgesLanguage(lang);
  });

  /* ─── MutationObserver: tự động inject khi DOM thay đổi ─────── */
  // (dùng cho archive-page.js và special-posts.js render bất đồng bộ)
  var _observer = null;
  function startObserver() {
    if (_observer) return;
    _observer = new MutationObserver(function (mutations) {
      var needsInject = mutations.some(function (m) {
        return m.addedNodes.length > 0;
      });
      if (needsInject) {
        injectTimelineBadges();
        injectWidgetBadges();
        injectPostCardBadges();
      }
    });
    _observer.observe(document.body, { childList: true, subtree: true });
  }

  /* ─── Utility: escape ────────────────────────────────────────── */
  function escapeHtml(str) {
    if (!str) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
  }

  function escapeAttr(str) {
    if (!str) return '';
    return String(str).replace(/"/g, '&quot;').replace(/'/g, '&#039;');
  }

  /* ─── Export API cho các module khác ───────────────────────── */
  window.AITransparency = {
    detectAIType: detectAIType,
    detectAITypeFromLabels: detectAITypeFromLabels,
    renderAIBadge: renderAIBadge,
    renderDisclosureBox: renderDisclosureBox,
    injectTimelineBadges: injectTimelineBadges,
    injectWidgetBadges: injectWidgetBadges,
    injectPostCardBadges: injectPostCardBadges,
    reinject: initAITransparency,
  };

  /* ─── Khởi động ─────────────────────────────────────────────── */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () {
      initAITransparency();
      startObserver();
    });
  } else {
    initAITransparency();
    startObserver();
  }

})();
