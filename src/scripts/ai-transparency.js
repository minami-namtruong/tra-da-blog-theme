  /* ─── Chuẩn hóa nhãn AI (không phân biệt hoa thường, hỗ trợ dấu gạch ngang) */
  function normalizeAILabel(str) {
    if (!str) return '';
    return str.toLowerCase().replace(/-/g, ':');
  }

  /* ─── Phát hiện loại AI từ chuỗi nhãn đơn ─────────────────── */
  function detectAIType(labelStr) {
    var normalized = normalizeAILabel(labelStr.trim());
    // Khớp trực tiếp
    if (AI_TYPES[normalized]) return normalized;
    // Khớp từng key
    var keys = Object.keys(AI_TYPES);
    for (var i = 0; i < keys.length; i++) {
      if (normalized.indexOf(keys[i].replace(':', ':')) === 0 ||
          normalized.indexOf(keys[i].replace(':', '-')) === 0) {
        return keys[i];
      }
    }
    return null;
  }

  /* ─── Phát hiện loại AI từ mảng nhãn ───────────────────────── */
  function extractAITypesFromLabels(labels) {
    if (!labels || !labels.length) return null;
    var foundContent = null;
    var foundProduct = null;
    var priority = ['ai:generated', 'ai:product', 'ai:contributed', 'ai:assisted', 'ai:translated'];
    for (var i = 0; i < labels.length; i++) {
      var raw = (typeof labels[i] === 'string') ? labels[i] : (labels[i].name || '');
      var type = detectAIType(raw);
      if (type) {
        if (type === 'ai:product') {
          foundProduct = type;
        } else {
          if (!foundContent || priority.indexOf(type) < priority.indexOf(foundContent)) {
            foundContent = type;
          }
        }
      }
    }
    var res = [];
    if (foundContent) res.push(foundContent);
    if (foundProduct) res.push(foundProduct);
    return res.length > 0 ? res.join(',') : null;
  }

  /* ─── Render Badge HTML ─────────────────────────────────────── */
  /**
   * @param {string} type     - 'ai:contributed' | 'ai:product' | 'ai:generated'
   * @param {string} variant  - 'full' | 'standard' | 'micro' | 'inline'
   * @param {string} lang     - 'vi' | 'en'
   * @returns {string} HTML string
   */
  function renderAIBadge(type, variant, lang) {
    type = detectAIType(type) || type;
    var cfg = AI_TYPES[type];
    if (!cfg) return '';

    var label = (lang === 'en') ? cfg.en : cfg.vi;
    var icon  = cfg.icon;
    var displayAttr = (type === 'ai:translated' && lang === 'vi') ? ' style="display: none;"' : '';

    if (variant === 'inline') {
      return (
        '<span class="ai-badge ai-badge-inline" data-ai-type="' + type + '" data-ai-variant="inline"' + displayAttr + '>' +
          '<span class="ai-badge-icon">' + icon + '</span>' +
          '<span class="ai-badge-label">AI</span>' +
        '</span>'
      );
    }

    if (variant === 'micro') {
      return (
        '<span class="ai-badge ai-badge-micro" data-ai-type="' + type + '" data-ai-variant="micro"' + displayAttr + '>' +
          '<span class="ai-badge-icon">' + icon + '</span>' +
          '<span class="ai-badge-label">AI</span>' +
        '</span>'
      );
    }

    if (variant === 'full') {
      return (
        '<button type="button" class="ai-badge ai-badge-full" data-ai-type="' + type + '" data-ai-variant="full" aria-expanded="false"' + displayAttr + '>' +
          '<span class="ai-badge-icon">' + icon + '</span>' +
          '<span class="ai-badge-label">' + label + '</span>' +
          '<span class="ai-badge-chevron">▾</span>' +
        '</button>'
      );
    }

    // standard (default)
    return (
      '<span class="ai-badge ai-badge-standard" data-ai-type="' + type + '" data-ai-variant="standard"' + displayAttr + '>' +
        '<span class="ai-badge-icon">' + icon + '</span>' +
        '<span class="ai-badge-label">' + label + '</span>' +
      '</span>'
    );
  }

